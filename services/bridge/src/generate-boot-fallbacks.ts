import { createHash } from "node:crypto";
import { mkdir, rename, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { loadSpeechConfig } from "./config.js";
import { FALLBACK_VERSION, synthesizeSpeech } from "./startup-greeting.js";

type Period = "morning" | "afternoon" | "evening";
type Cause = "bluetooth_disabled" | "assistant_unavailable";

const periods: Period[] = ["morning", "afternoon", "evening"];
const causes: Cause[] = ["bluetooth_disabled", "assistant_unavailable"];
const repositoryRoot = fileURLToPath(new URL("../../../../", import.meta.url));
const outputDirectory = join(repositoryRoot, "apps/glass/src/main/res/raw");
const metadataPath = join(repositoryRoot, "docs/assets/startup-fallbacks.json");

function text(period: Period, cause: Cause): string {
  const reason = cause === "bluetooth_disabled"
    ? "Bluetooth appears to be disabled."
    : "The local assistant is unavailable.";
  return `Good ${period}, sir. ${reason}`;
}

async function writeAtomically(path: string, bytes: Uint8Array): Promise<void> {
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, bytes, { mode: 0o644 });
  await rename(temporary, path);
}

async function main(): Promise<void> {
  const config = loadSpeechConfig();
  await mkdir(outputDirectory, { recursive: true });
  await mkdir(join(repositoryRoot, "docs/assets"), { recursive: true });
  const clips: Array<Record<string, string | number>> = [];
  for (const period of periods) {
    for (const cause of causes) {
      const spokenText = text(period, cause);
      const audio = await synthesizeSpeech(config, fetch, new AbortController().signal, spokenText, 128 * 1024);
      const filename = `startup_${period}_${cause}.mp3`;
      await writeAtomically(join(outputDirectory, filename), audio);
      clips.push({
        filename,
        text: spokenText,
        bytes: audio.byteLength,
        sha256: createHash("sha256").update(audio).digest("hex"),
      });
    }
  }
  const metadata = {
    version: FALLBACK_VERSION,
    provider: "ElevenLabs",
    model: config.elevenLabsModelId,
    generatedAt: new Date().toISOString(),
    licenseBasis: "Generated by the project owner under an active ElevenLabs Creator plan using a licensed original voice; no cloned or impersonated voice.",
    clips,
  };
  await writeAtomically(metadataPath, new TextEncoder().encode(`${JSON.stringify(metadata, null, 2)}\n`));
  process.stdout.write(`Generated ${clips.length} licensed startup clips and metadata.\n`);
}

await main();
